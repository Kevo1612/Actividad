--  TABLA REGION
CREATE TABLE REGION (
    ID_REGION NUMBER(4) PRIMARY KEY,
    NOM_REGION VARCHAR2(225) NOT NULL,
    CONSTRAINT UQ_REGION_NOMBRE UNIQUE (NOM_REGION)
);
--SECUENCIA PARA ID DE REGION
CREATE SEQUENCE SEQ_REGION
START WITH 21
INCREMENT BY 1
NOCACHE;

--  TABLA COMUNA
CREATE TABLE COMUNA (
    ID_COMUNA NUMBER(4) GENERATED BY DEFAULT AS IDENTITY
        (START WITH 1050 INCREMENT BY 5)  PRIMARY KEY,
    NOM_COMUNA VARCHAR2(100) NOT NULL,
    REGION_ID NUMBER(4) NOT NULL,
    CONSTRAINT FK_COMUNA_REGION FOREIGN KEY (REGION_ID)
        REFERENCES REGION(ID_REGION)
);

--  TABLA PLANTA
CREATE TABLE PLANTA (
    ID_PLANTA NUMBER(4) PRIMARY KEY,
    NOM_PLANTA VARCHAR2(225) NOT NULL,
    DIRECCION VARCHAR2(200) NOT NULL,
    COMUNA_ID NUMBER(4) NOT NULL,
    CONSTRAINT FK_PLANTA_COMUNA FOREIGN KEY (COMUNA_ID)
        REFERENCES COMUNA(ID_COMUNA)
);

--  TABLA AFP
CREATE TABLE AFP (
    ID_AFP NUMBER(4) PRIMARY KEY,
    NOM_AFP VARCHAR2(255) NOT NULL,
    CONSTRAINT UQ_AFP_NOMBRE UNIQUE (NOM_AFP)
);

--  TABLA SALUD
CREATE TABLE SALUD (
    ID_SALUD NUMBER(4) PRIMARY KEY,
    NOM_SALUD VARCHAR2(100) NOT NULL,
    CONSTRAINT UQ_SALUD_NOMBRE UNIQUE (NOM_SALUD)
);

--  TABLA EMPLEADO
CREATE TABLE EMPLEADO (
    ID_EMPLEADO NUMBER(4) PRIMARY KEY,
    RUT_EMPLEADO VARCHAR2(12) UNIQUE NOT NULL,
    NOMBRE VARCHAR2(25) NOT NULL,
    APELLIDOS VARCHAR2(50) NOT NULL,
    FECHA_CONTRATACION DATE NOT NULL,
    SUELDO_BASE NUMBER(10,2) NOT NULL,
    ESTADO_ACTIVO CHAR(1) DEFAULT 'S' CHECK (ESTADO_ACTIVO IN ('S','N')),
    AFP_ID NUMBER(4) NOT NULL,
    SALUD_ID NUMBER(4) NOT NULL,
    PLANTA_ID NUMBER(4) NOT NULL,
    JEFE_ID NUMBER(4),
    CONSTRAINT FK_EMPLEADO_AFP FOREIGN KEY (AFP_ID) REFERENCES AFP(ID_AFP),
    CONSTRAINT FK_EMPLEADO_SALUD FOREIGN KEY (SALUD_ID) REFERENCES SALUD(ID_SALUD),
    CONSTRAINT FK_EMPLEADO_PLANTA FOREIGN KEY (PLANTA_ID) REFERENCES PLANTA(ID_PLANTA),
    CONSTRAINT FK_EMPLEADO_JEFE FOREIGN KEY (JEFE_ID) REFERENCES EMPLEADO(ID_EMPLEADO)
);

--  TABLA EQUIPO
CREATE TABLE EQUIPO (
    ID_EQUIPO NUMBER(4) PRIMARY KEY,
    NOM_EQUIPO VARCHAR2(100) NOT NULL,
    TIPO_EQUIPO VARCHAR2(50),
    ESTADO_ACTIVO CHAR(1) DEFAULT 'S' CHECK (ESTADO_ACTIVO IN ('S','N')),
    CODIGO_UNICO NUMBER UNIQUE NOT NULL,
    PLANTA_ID NUMBER(4) NOT NULL,
    CONSTRAINT UQ_EQUIPO_TIPO UNIQUE (TIPO_EQUIPO),
    CONSTRAINT FK_EQUIPO_PLANTA FOREIGN KEY (PLANTA_ID)
        REFERENCES PLANTA(ID_PLANTA)
);

--  TABLA ROL
CREATE TABLE ROL (
    ID_ROL NUMBER(4) PRIMARY KEY,
    NOM_ROL VARCHAR2(50) NOT NULL
);

--  TABLA TURNO
CREATE TABLE TURNO (
    ID_TURNO VARCHAR2(10) PRIMARY KEY,
    NOM_TURNO VARCHAR2(10) NOT NULL,
    HORA_INICIO CHAR(5) NOT NULL,
    HORA_TERMINO CHAR(5) NOT NULL,
    CONSTRAINT UQ_TURNO_NOMBRE UNIQUE (NOM_TURNO)
);

--  TABLA ASIGNACION_TURNO
CREATE TABLE ASIGNACION_TURNO (
    ID_ASIGNACION NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FECHA_ASIG DATE NOT NULL,
    TURNO_ID NUMBER(4) NOT NULL,
    EMPLEADO_ID NUMBER(4) NOT NULL,
    EQUIPO_ID NUMBER(4) NOT NULL,
    ROL_ID NUMBER(4) NOT NULL,
    CONSTRAINT FK_ASIG_TURNO FOREIGN KEY (TURNO_ID) REFERENCES TURNO(ID_TURNO),
    CONSTRAINT FK_ASIG_EMPLEADO FOREIGN KEY (EMPLEADO_ID) REFERENCES EMPLEADO(ID_EMPLEADO),
    CONSTRAINT FK_ASIG_EQUIPO FOREIGN KEY (EQUIPO_ID) REFERENCES EQUIPO(ID_EQUIPO),
    CONSTRAINT FK_ASIG_ROL FOREIGN KEY (ROL_ID) REFERENCES ROL(ID_ROL)
);

--  TABLA TECNICO_MANTENCION
CREATE TABLE TECNICO_MANTENCION (
    ID_TECNICO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPLEADO_ID NUMBER(4) NOT NULL,
    ESPECIALIDAD VARCHAR2(50) NOT NULL,
    NIVEL_CERTIFICACION NUMBER(1) CHECK (NIVEL_CERTIFICACION BETWEEN 1 AND 5),
    TIEMPO_RESPUESTA NUMBER(4) NOT NULL,
    CONSTRAINT FK_TECNICO_EMPLEADO FOREIGN KEY (EMPLEADO_ID)
        REFERENCES EMPLEADO(ID_EMPLEADO)
);

--  TABLA ORDEN_MANTENCION
CREATE TABLE ORDEN_MANTENCION (
    ID_ORDEN NUMBER(4) PRIMARY KEY,
    FECHA_PROGRAMADA DATE NOT NULL,
    FECHA_EJECUCION DATE,
    TIPO_MANTENCION VARCHAR2(15) NOT NULL,
    DESCRIPCION VARCHAR2(200) NOT NULL,
    EQUIPO_ID NUMBER(4) NOT NULL,
    TECNICO_ID NUMBER NOT NULL,
    CONSTRAINT FK_ORDEN_EQUIPO FOREIGN KEY (EQUIPO_ID)
        REFERENCES EQUIPO(ID_EQUIPO),
    CONSTRAINT FK_ORDEN_TECNICO FOREIGN KEY (TECNICO_ID)
        REFERENCES TECNICO_MANTENCION(ID_TECNICO)
);

--  TABLA JEFE_TURNO
CREATE TABLE JEFE_TURNO (
    ID_JEFE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPLEADO_ID NUMBER(4) NOT NULL,
    AREA_RESPONSABILIDAD VARCHAR2(100) NOT NULL,
    MAX_OPERARIOS NUMBER(3) NOT NULL,
    CONSTRAINT FK_JEFE_EMPLEADO FOREIGN KEY (EMPLEADO_ID)
        REFERENCES EMPLEADO(ID_EMPLEADO)
);

--  TABLA OPERARIO
CREATE TABLE OPERARIO (
    ID_OPERARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPLEADO_ID NUMBER(4) NOT NULL,
    CATEGORIA_PROCESO VARCHAR2(50) NOT NULL,
    CERTIFICACION VARCHAR2(100),
    HORAS_TURNO NUMBER(3) NOT NULL,
    CONSTRAINT FK_OPERARIO_EMPLEADO FOREIGN KEY (EMPLEADO_ID)
        REFERENCES EMPLEADO(ID_EMPLEADO)
);

--TRIGGER PARA VALIDACION DE FECHAS EN TABLA ORDEN_MANTENCION
CREATE OR REPLACE TRIGGER TRG_VALIDAR_FECHAS_ORDEN
BEFORE INSERT OR UPDATE ON ORDEN_MANTENCION
FOR EACH ROW
BEGIN
    IF :NEW.FECHA_EJECUCION IS NOT NULL THEN
        IF :NEW.FECHA_EJECUCION < :NEW.FECHA_PROGRAMADA THEN
            RAISE_APPLICATION_ERROR(-20001,
                'La fecha de ejecución no puede ser anterior a la fecha programada.');
        END IF;
    END IF;
END;
