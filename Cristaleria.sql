SELECT 
    ID_TURNO || ' - ' || NOM_TURNO AS TURNO,
    HORA_INICIO AS ENTRADA,
    HORA_TERMINO AS SALIDA
FROM 
    TURNO
WHERE TO_DATE
    (HORA_INICIO, 'HH24:MI') > TO_DATE('20:00', 'HH24:MI')
ORDER BY TO_DATE
    (HORA_INICIO, 'HH24:MI') DESC;

