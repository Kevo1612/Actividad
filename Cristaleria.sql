    NOM_TURNO || ' (' || ID_TURNO || ')' AS TURNO,
    HORA_INICIO AS ENTRADA,
    HORA_TERMINO AS SALIDA
FROM 
    TURNO
WHERE TO_DATE
    (HORA_INICIO, 'HH24:MI') BETWEEN TO_DATE('06:00', 'HH24:MI') AND TO_DATE('14:59', 'HH24:MI')
ORDER BY TO_DATE
    (HORA_INICIO, 'HH24:MI') ASC;
